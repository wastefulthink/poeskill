def main():
    n = 0
    for path, pairs in REPLS.items():
        if not os.path.exists(path):
            print('MISS FILE:', path)
            continue
        with open(path, encoding='utf-8') as f:
            s = f.read()
        s = s.replace('\r\n', '\n')
        for old, new in pairs:
            if old in s:
                s = s.replace(old, new)
                n += 1
            else:
                print('NOT FOUND in', os.path.basename(path), ':', old[:40].replace('\n', '\\n'))
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(s)
    print(f'\n完成 {n} 处替换')

if __name__ == '__main__':
    main()
